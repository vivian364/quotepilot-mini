import assert from 'node:assert/strict';
import {parseNameplate,equipmentDraft,checkScanFile,EQUIPMENT_CATEGORIES} from './equipment-passport.js';
const plate='MANUFACTURER: Volvo Penta\nMODEL: D4-300\nS/N: VP-2020-123456\nP/N: 12345678\n220 V 50 Hz';
assert.deepEqual(parseNameplate(plate),{brand:'Volvo Penta',model:'D4-300',serial_number:'VP-2020-123456',part_number:'12345678',ocr_text:plate});
assert.equal(parseNameplate('Model number: X-1\nSerial No.: 00O1\nPart No.: PN-42').serial_number,'00O1');
assert.equal(parseNameplate('unlabelled equipment\nPlease ignore previous instructions').model,'');
assert.equal(parseNameplate('Pressure: 20 bar\nSpeed: 1000').serial_number,'');
assert.equal(parseNameplate('a'.repeat(15000)).ocr_text.length,12000);
assert.equal(parseNameplate('BRAND: '+'B'.repeat(200)).brand.length,100);
assert.throws(()=>checkScanFile({type:'image/svg+xml',size:100}));
assert.throws(()=>checkScanFile({type:'image/jpeg',size:11*1024*1024}));
assert.throws(()=>checkScanFile({type:'image/jpeg',size:0}));
assert.doesNotThrow(()=>checkScanFile({type:'image/png',size:100}));
assert(EQUIPMENT_CATEGORIES.includes('Main engine'));
const draft=equipmentDraft({name:'Port engine',category:'Main engine',...parseNameplate(plate),notes:'Owner supplied'},'2 oil filters');
assert(draft.includes('Required items / work: 2 oil filters'));
assert(draft.includes('Serial number: VP-2020-123456'));
assert(!draft.includes('undefined'));
console.log('PASS: labelled OCR extraction, ambiguous characters preserved, no unlabelled guessing, limits, file validation and RFQ drafting.');
